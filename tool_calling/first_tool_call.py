
"""
LESSON 16 - PART 1: FIRST LLM TOOL CALL
======================================

OBJECTIVE:
Understand how an LLM selects a Python function,
how Python executes it, and how the result is
returned to the LLM.

CONCEPTS:
1. Defining a Python tool
2. Passing tools to Ollama
3. Understanding response.message.tool_calls
4. Extracting function names and arguments
5. Executing approved functions
6. Sending tool results back to the LLM

MODEL:
qwen2:7b

RUN FROM PROJECT ROOT:
python -m tool_calling.first_tool_call

NOTE:
All insurance claim records are fictional.
"""

import json

from ollama import chat


# --------------------------------------------------
# STEP 1: CREATE SAMPLE CLAIM DATA
# --------------------------------------------------

# In a real application this information might
# come from Snowflake, PostgreSQL or an API.

CLAIMS_DATABASE = {
    "CLM1001": {
        "status": "Under Review",
        "claim_type": "Motor Accident",
        "amount": 4500
    },
    "CLM1002": {
        "status": "Approved",
        "claim_type": "Windshield Damage",
        "amount": 850
    },
    "CLM1003": {
        "status": "Rejected",
        "claim_type": "Mechanical Breakdown",
        "amount": 2200
    }
}


# --------------------------------------------------
# STEP 2: DEFINE OUR PYTHON TOOL
# --------------------------------------------------

def get_claim_status(claim_id: str) -> dict:
    """
    Look up a fictional motor insurance claim.

    Args:
        claim_id: Insurance claim identifier,
                  e.g. CLM1001.

    Returns:
        A dictionary containing claim details,
        or an error if the claim doesn't exist.
    """

    print(f"\n[PYTHON] Looking up claim: {claim_id}")

    claim = CLAIMS_DATABASE.get(claim_id)

    if claim is None:
        return {
            "claim_id": claim_id,
            "error": "Claim not found"
        }

    return {
        "claim_id": claim_id,
        **claim
    }


# --------------------------------------------------
# STEP 3: REGISTER APPROVED TOOLS
# --------------------------------------------------

# Our application decides which functions the
# LLM is allowed to request.
#
# We never execute arbitrary function names.

AVAILABLE_TOOLS = {
    "get_claim_status": get_claim_status
}


# --------------------------------------------------
# STEP 4: RECEIVE THE USER QUESTION
# --------------------------------------------------

question = "What is an insurance deductible"

messages = [
    {
        "role": "system",
        "content": (
            "You are an insurance claim assistant. "
            "Use the available tool for claim status "
            "questions. Do not invent claim details."
        )
    },
    {
        "role": "user",
        "content": question
    }
]

print("\nUSER QUESTION:")
print(question)


# --------------------------------------------------
# STEP 5: ASK THE LLM TO SELECT A TOOL
# --------------------------------------------------

response = chat(
    model="qwen2:7b",
    messages=messages,
    tools=[get_claim_status],
    options={"temperature": 0}
)


# --------------------------------------------------
# STEP 6: INSPECT AND EXECUTE TOOL CALLS
# --------------------------------------------------

tool_calls = response.message.tool_calls or []

if not tool_calls:

    print("\nNo structured tool call returned.")
    print("Model response:")
    print(response.message.content)

else:

    # Keep the assistant's tool-call message
    # in the conversation history.
    messages.append(response.message)

    for tool_call in tool_calls:

        function_name = tool_call.function.name
        function_args = tool_call.function.arguments

        print("\nTOOL SELECTED BY LLM:")
        print(function_name)

        print("\nARGUMENTS GENERATED BY LLM:")
        print(function_args)

        # Only execute explicitly approved functions.
        function = AVAILABLE_TOOLS.get(function_name)

        if function is None:
            result = {
                "error": f"Unknown tool: {function_name}"
            }

        else:
            # Validate the expected argument before
            # passing it into our Python function.
            claim_id = function_args.get("claim_id")

            if not isinstance(claim_id, str):
                result = {
                    "error": "claim_id must be a string"
                }
            else:
                result = function(
                    claim_id=claim_id
                )

        print("\nPYTHON TOOL RESULT:")
        print(result)

        # Return the tool result to the model.
        messages.append({
            "role": "tool",
            "tool_name": function_name,
            "content": json.dumps(result)
        })

    # ----------------------------------------------
    # STEP 7: GET FINAL NATURAL-LANGUAGE ANSWER
    # ----------------------------------------------

    final_response = chat(
        model="qwen2:7b",
        messages=messages,
        options={"temperature": 0}
    )

    print("\nFINAL AI RESPONSE:")
    print(final_response.message.content)
