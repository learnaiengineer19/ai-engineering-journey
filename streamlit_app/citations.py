
"""
LESSON 14 - PART 9: CITATION VALIDATION
=======================================

OBJECTIVE:
Validate source citations generated by our
Advanced RAG insurance policy assistant.

CONCEPTS:
1. Regular expressions (re.findall)
2. Extracting citation numbers
3. Validating references against retrieved sources
4. Removing duplicate citations using set()
5. Separating reusable logic from Streamlit UI

EXAMPLE:
    Answer:
        "Mechanical breakdown is excluded [Source 1].
         Additional conditions apply [Source 2]."

    Available sources:
        3 PDF chunks

    Result:
        valid_numbers = [1, 2]
        invalid_numbers = []

IMPORTANT:
This function validates citation references,
not the factual correctness of the AI answer.

RUN TESTS:
python -m pytest streamlit_app/test_citations.py -v
"""

import re


# --------------------------------------------------
# STEP 1: ANALYSE ANSWER CITATIONS
# --------------------------------------------------

def analyse_citations(
    answer: str,
    sources: list[dict]
) -> dict:
    """
    Extract citations from an AI-generated answer
    and validate them against available PDF chunks.

    Args:
        answer:
            AI-generated response containing references
            such as [Source 1], [Source 2], etc.

        sources:
            List of retrieved PDF chunks used to
            construct the LLM context.

    Returns:
        Dictionary containing:
        - cited_numbers: All unique citation numbers
        - valid_numbers: Citations pointing to sources
        - invalid_numbers: Citations outside source range
        - has_citations: Whether citations were detected
    """

    # ----------------------------------------------
    # STEP 2: EXTRACT CITATION NUMBERS
    # ----------------------------------------------

    # Example:
    # "See [Source 1] and [Source 2]"
    #
    # re.findall returns ["1", "2"].

    matches = re.findall(
        r"\[Source\s+(\d+)\]",
        answer
    )

    # ----------------------------------------------
    # STEP 3: CONVERT TO UNIQUE SORTED INTEGERS
    # ----------------------------------------------

    # int() converts "1" to 1.
    # set() removes duplicates.
    # sorted() orders numbers ascending.

    cited_numbers = sorted(
        set(int(number) for number in matches)
    )

    # ----------------------------------------------
    # STEP 4: VALIDATE CITATIONS
    # ----------------------------------------------

    # Source numbering starts at 1.
    #
    # If three chunks were retrieved:
    # Valid references are [1], [2], [3].

    valid_numbers = [
        number
        for number in cited_numbers
        if 1 <= number <= len(sources)
    ]

    invalid_numbers = [
        number
        for number in cited_numbers
        if number < 1 or number > len(sources)
    ]

    # ----------------------------------------------
    # STEP 5: RETURN STRUCTURED RESULTS
    # ----------------------------------------------

    return {
        "cited_numbers": cited_numbers,
        "valid_numbers": valid_numbers,
        "invalid_numbers": invalid_numbers,
        "has_citations": len(cited_numbers) > 0
    }
